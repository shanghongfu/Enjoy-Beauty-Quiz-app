const I18N_LANGS = ['en', 'es', 'vi', 'zh', 'ko'];
const I18N_LANG_NAMES = { en: 'English', es: 'Español', vi: 'Tiếng Việt', zh: '中文', ko: '한국어' };
const I18N_LANG_FLAGS = { en: '🇺🇸', es: '🇪🇸', vi: '🇻🇳', zh: '🇨🇳', ko: '🇰🇷' };

const i18n = {
  current: 'en',

  // Alias used across the app (loadQuestions / save). Fixes the bug where
  // `window.i18n.currentLang` was always undefined → always fell back to 'en'.
  get currentLang() { return this.current; },

  t(key, params) {
    const dict = I18N_DICT[this.current] || I18N_DICT.en;
    let s = dict[key];
    if (s === undefined) s = I18N_DICT.en[key] !== undefined ? I18N_DICT.en[key] : key;
    if (params) {
      Object.keys(params).forEach(k => {
        s = s.split('{' + k + '}').join(String(params[k]));
      });
    }
    return s;
  },

  setLanguage(lang) {
    if (!I18N_DICT[lang]) lang = 'en';
    this.current = lang;
    try { localStorage.setItem('quiz_master_lang', lang); } catch (e) {}
    document.documentElement.lang = lang;
    this.apply();
    // Notify listeners (e.g. refresh questions in new language)
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    // Persist to server (fire-and-forget)
    if (window.db && window.db.auth && window.db.auth.getUser) {
      window.db.auth.getUser().then(({ data: { user } }) => {
        if (user) {
          window.db.from('users').update({ preferred_language: lang }).eq('id', user.id)
            .then(() => {}, () => {});
        }
      });
    }
  },

  apply() {
    // data-i18n="key" → element text
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(el.dataset.i18n);
    });
    // data-i18n-placeholder="key" → input placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    });
    // data-i18n-title="key" → title attribute
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.dataset.i18nTitle);
    });
    // data-i18n-html="key" → innerHTML (use carefully)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = this.t(el.dataset.i18nHtml);
    });
    // Lang menu sub
    const sub = document.getElementById('currentLangSub');
    if (sub) {
      const flag = (window.I18N_LANG_FLAGS || {})[this.current] || '';
      const name = (window.I18N_LANG_NAMES || {})[this.current] || this.current;
      sub.textContent = flag + ' ' + name;
    }
  },

  detect() {
    try {
      const stored = localStorage.getItem('quiz_master_lang');
      if (stored && I18N_DICT[stored]) return stored;
    } catch (e) {}
    const nav = (navigator.language || 'en').toLowerCase();
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('vi')) return 'vi';
    if (nav.startsWith('ko')) return 'ko';
    if (nav.startsWith('en')) return 'en';
    return 'en';
  },

  async loadUserPreference() {
    // If logged in, prefer server-stored language over localStorage
    if (!window.db || !window.db.auth) return;
    try {
      const { data: { user } } = await window.db.auth.getUser();
      if (!user) return;
      const { data } = await window.db.from('users').select('preferred_language').eq('id', user.id).maybeSingle();
      if (data && data.preferred_language && I18N_DICT[data.preferred_language]) {
        this.current = data.preferred_language;
        try { localStorage.setItem('quiz_master_lang', this.current); } catch (e) {}
        document.documentElement.lang = this.current;
      }
    } catch (e) {}
  }
};

window.i18n = i18n;
window.I18N_LANGS = I18N_LANGS;
window.I18N_LANG_NAMES = I18N_LANG_NAMES;
window.I18N_LANG_FLAGS = I18N_LANG_FLAGS;
